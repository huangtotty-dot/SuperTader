def main():
    wl = json.loads(WL.read_text(encoding="utf-8"))
    bak = BASE / "backup" / f"watchlist_concept_before_litho_roles_{datetime.now():%Y%m%d_%H%M%S}.json"
    bak.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(WL, bak)
    done, skipped = [], []
    for code, (role, reason) in ROLES.items():
        e = wl.get(code)
        if not isinstance(e, dict):
            skipped.append((code, "不在 watchlist"))
            continue
        if str(e.get("role") or "").strip() in ("龙头", "中军"):
            skipped.append((code, f"已有角色 {e.get('role')}（只增不改）"))
            continue
        e["role"] = role
        e["role_reason"] = reason
        done.append((code, e.get("name"), role))
    wl["updated_at"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    WL.write_text(json.dumps(wl, ensure_ascii=False, indent=1), encoding="utf-8")
    for c, n, r in done:
        print(f"{c} {n} → {r}")
    print(f"写入 {len(done)} 只；跳过 {len(skipped)}：{skipped}")
    print(f"[backup] {bak}")


if __name__ == "__main__":
    main()
