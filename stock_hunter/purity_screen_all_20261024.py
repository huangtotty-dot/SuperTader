def keywords(concept):
    parts = []
    for seg in concept.replace("|", "_").replace("-", "_").split("_"):
        seg = seg.strip()
        if len(seg) >= 2:
            parts.append(seg)
    parts += SYN.get(concept, [])
    for pre, kws in FAMILY:
        if concept.startswith(pre):
            parts += kws
    # 中文复合词很常见（存储封测↔存储半导体、半导体洁净室↔半导体）⇒ 再加 2 字前缀
    parts += [p[:2] for p in list(parts) if len(p) >= 4]
    return [p for p in dict.fromkeys(parts) if p]


def main():
    apply = "--apply" in sys.argv
    wl = json.load(open(WL, encoding="utf-8"))
    try:
        prof = json.load(open(PROF, encoding="utf-8"))
    except Exception:
        prof = {}
    rows, per_cat = [], defaultdict(lambda: [0, 0])   # cat -> [有据, 无据]
    for code, rec in wl.items():
        if not isinstance(rec, dict):
            continue
        cons = []
        cat = ""
        for i in list(range(1, 10)) + [0]:
            k = "jiuyan_category" if i == 0 else f"jiuyan_category{i}"
            ck = "jiuyan_concept" if i == 0 else f"jiuyan_concept{i}"
            c = str(rec.get(k) or "").strip()
            v = rec.get(ck)
            toks = v if isinstance(v, list) else str(v or "").split("|")
            toks = [str(t).strip() for t in toks if str(t).strip()]
            if c and toks:
                cat = cat or c.split("|")[0]
                cons += toks
        if not cons:
            continue
        p = prof.get(code) or {}
        text = " ".join([str(p.get("brief_title") or ""), str(p.get("brief") or ""),
                         str(p.get("points") or "")[:600],
                         str(rec.get("business_summary") or ""), str(rec.get("sector") or "")])
        kws = [kw for c in cons for kw in keywords(c) if kw]
        if not kws:      # 概念本身没有可比对的关键词（其他/国家队…）⇒ 不计入统计
            continue
        hit = any(kw in text for kw in kws)
        per_cat[cat][0 if hit else 1] += 1
        if hit:
            rec["jiuyan_tag_evidence"] = "text"
        if not hit:
            rows.append([code, rec.get("name") or "", cat, "|".join(dict.fromkeys(cons)),
                         text.strip()[:80]])

    print(f"{'板块':10s} {'有据':>5s} {'无据':>5s} {'支持率':>7s}")
    for cat, (a, b) in sorted(per_cat.items(), key=lambda kv: -(kv[1][0] + kv[1][1])):
        tot = a + b
        print(f"{cat:10s} {a:5d} {b:5d} {a / tot * 100:6.1f}%")
    print(f"\n无据候选 {len(rows)} 只 → {OUT}")
    if apply:
        import shutil
        bak = WL + ".bak_20261024_evidence"
        if not os.path.exists(bak):
            shutil.copy2(WL, bak)
        json.dump(wl, open(WL, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"已写入 jiuyan_tag_evidence。备份: {bak}")
    with open(OUT.replace(".csv", "_板块汇总.csv"), "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["板块", "有据", "无据", "支持率%"])
        for cat, (a, b) in sorted(per_cat.items(), key=lambda kv: -(kv[1][0] + kv[1][1])):
            w.writerow([cat, a, b, round(a / (a + b) * 100, 1)])
    with open(OUT, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["代码", "名称", "板块", "概念", "业务文本(截断)"])
        w.writerows(rows)


if __name__ == "__main__":
    main()
