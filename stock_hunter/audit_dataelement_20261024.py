def _dataelement_concepts(rec):
    out = []
    for i in range(0, 10):
        k = "jiuyan_category" if i == 0 else f"jiuyan_category{i}"
        ck = "jiuyan_concept" if i == 0 else f"jiuyan_concept{i}"
        if "数据要素" not in str(rec.get(k) or ""):
            continue
        con = rec.get(ck)
        toks = con if isinstance(con, list) else str(con or "").split("|")
        out += [str(t).strip() for t in toks if str(t).strip()]
    return out


def main():
    apply = "--apply" in sys.argv
    data = json.load(open(SRC, encoding="utf-8"))
    changed, skipped, missing = [], [], []
    for code, (verdict, reason) in AUDIT.items():
        rec = data.get(code)
        if not isinstance(rec, dict):
            missing.append(code)
            continue
        cons = _dataelement_concepts(rec)
        d = rec.get("jiuyan_concept_reason")
        if not isinstance(d, dict):
            d = {}
        add = {c: reason for c in cons if not str(d.get(c) or "").strip()}
        rec["jiuyan_dataelement_verdict"] = verdict
        if add:
            changed.append((code, rec.get("name"), verdict, list(add)))
            if apply:
                d.update(add)
                rec["jiuyan_concept_reason"] = d
                rec["updated_at"] = MARK
        else:
            skipped.append((code, rec.get("name")))

    print(f"写理由 {len(changed)} 只；已有理由跳过 {len(skipped)} 只；不在表 {missing}")
    dist = Counter(v for v, _ in AUDIT.values())
    print("纯正性分布：", dict(dist))
    for code, name, verdict, cons in changed[:10]:
        print(f"  {code} {name:<7s} [{verdict}] {'/'.join(cons)}")
    if len(changed) > 10:
        print(f"  …… 其余 {len(changed) - 10} 只")

    if not apply:
        print("\n(dry-run，未写文件；加 --apply 执行)")
        return
    for code, kv in FIX_FIELDS.items():
        rec = data.get(code)
        if isinstance(rec, dict):
            rec.update(kv)
            rec["updated_at"] = MARK
    if not os.path.exists(BAK):
        shutil.copy2(SRC, BAK)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\n已写入。备份: {BAK}")


if __name__ == "__main__":
    main()
