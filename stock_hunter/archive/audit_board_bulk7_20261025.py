def concepts_of(rec):
    out = []
    for i in list(range(1, 10)) + [0]:
        ck = "jiuyan_concept" if i == 0 else f"jiuyan_concept{i}"
        v = rec.get(ck)
        out += [str(t).strip() for t in (v if isinstance(v, list) else str(v or "").split("|")) if str(t).strip()]
    return list(dict.fromkeys(out))


def main():
    apply = "--apply" in sys.argv
    data = json.load(open(SRC, encoding="utf-8"))
    RANK = {"核心": 3, "相关": 2, "边缘": 1}
    best, dist = {}, Counter()

    def put(code, verdict, reason):
        cur = best.get(code)
        if cur is None or RANK[verdict] > RANK[cur[0]]:
            best[code] = (verdict, reason)
        dist[verdict] += 1

    for code, rec in data.items():
        if not isinstance(rec, dict) or rec.get("jiuyan_tag_verdict"):
            continue
        cats = [str(rec.get("jiuyan_category" if i == 0 else f"jiuyan_category{i}") or "")
                for i in list(range(1, 10)) + [0]]
        cons = concepts_of(rec)
        if not cons:
            continue
        if code in COAL and any("煤化工" in c for c in cats):
            put(code, *COAL[code]); continue
        if code in OVERRIDE:
            put(code, *OVERRIDE[code]); continue
        for board, (core, related) in RULES.items():
            if not any(board in c for c in cats):
                continue
            v = "边缘"
            for c in cons:
                if c in core:
                    v = "核心"; break
                if c in related and RANK["相关"] > RANK[v]:
                    v = "相关"
            if v != "边缘":
                put(code, v, "")
                break

    for code, (verdict, reason) in best.items():
        rec = data.get(code)
        if not isinstance(rec, dict):
            continue
        rec["jiuyan_tag_verdict"] = verdict
        if reason:
            d = rec.get("jiuyan_concept_reason")
            if not isinstance(d, dict):
                d = {}
            for c in concepts_of(rec):
                if not str(d.get(c) or "").strip() or str(d.get(c) or "").startswith("主营"):
                    d[c] = reason
            rec["jiuyan_concept_reason"] = d
        rec["updated_at"] = MARK

    print(f"写入 {len(best)} 只；{dict(dist)}")
    if not apply:
        print("\n(dry-run，未写文件；加 --apply 执行)")
        return
    if not os.path.exists(BAK):
        shutil.copy2(SRC, BAK)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\n已写入。备份: {BAK}")


if __name__ == "__main__":
    main()
