def main():
    apply = "--apply" in sys.argv
    data = json.load(open(SRC, encoding="utf-8"))
    log = []
    for code, (verdict, reason) in AUDIT.items():
        rec = data.get(code)
        if not isinstance(rec, dict):
            continue
        rec["jiuyan_tag_verdict"] = verdict
        d = rec.get("jiuyan_concept_reason")
        if not isinstance(d, dict):
            d = {}
        cons = []
        for i in list(range(1, 10)) + [0]:
            ck = "jiuyan_concept" if i == 0 else f"jiuyan_concept{i}"
            v = rec.get(ck)
            cons += [str(t).strip() for t in (v if isinstance(v, list) else str(v or "").split("|")) if str(t).strip()]
        add = {c: reason for c in dict.fromkeys(cons) if not str(d.get(c) or "").strip()}
        if add:
            d.update(add)
            rec["jiuyan_concept_reason"] = d
        rec["updated_at"] = MARK
        log.append((code, rec.get("name"), verdict, len(add)))

    print(f"写入 {len(log)} 只；判词分布 {dict(Counter(v for _, _, v, _ in log))}")
    if not apply:
        print("\n(dry-run，未写文件；加 --apply 执行)")
        return
    if not os.path.exists(BAK):
        shutil.copy2(SRC, BAK)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\n已写入。备份: {BAK}")


if __name__ == "__main__":
    main()
