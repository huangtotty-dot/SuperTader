def _toks(cons):
    return [t for c in cons for t in str(c).split("|") if t]


def _has(rec):
    for k, v in rec.items():
        if k == "jiuyan_concept" or (k.startswith("jiuyan_concept") and k[-1].isdigit()):
            if isinstance(v, str) and v.strip():
                return True
            if isinstance(v, list) and any(str(x).strip() for x in v):
                return True
    return False


def main():
    apply = "--apply" in sys.argv
    data = json.load(open(SRC, encoding="utf-8"))
    log, skipped = [], []
    for code, items in ADD.items():
        rec = data.get(code)
        if not rec:
            skipped.append((code, "?", "不在 watchlist")); continue
        if _has(rec):
            skipped.append((code, rec.get("name"), "已有概念标签，跳过（只增不改由后续批次处理）"))
            continue
        for cat, con in items:
            if "jiuyan_category" not in rec or not str(rec.get("jiuyan_category") or "").strip():
                rec["jiuyan_category"] = cat
                rec["jiuyan_concept"] = con
                rec["updated_at"] = "2026-10-24 12:00:00"
                log.append((code, rec.get("name"), f"（无标签）→ {cat}/{con}"))
            else:
                used = {int(k[len("jiuyan_category"):]) for k in rec
                        if k.startswith("jiuyan_category") and k[len("jiuyan_category"):].isdigit()}
                slot = next((i for i in range(1, 10) if i not in used), None)
                if slot is None:
                    skipped.append((code, rec.get("name"), "槽位已满")); continue
                rec[f"jiuyan_category{slot}"] = cat
                rec[f"jiuyan_concept{slot}"] = con
                log.append((code, rec.get("name"), f"追加 {cat}/{con}→slot{slot}"))

    for code, (name, cat, con) in MISSING.items():
        rec = data.get(code)
        if rec is None:
            rec = {"name": name, "primary_source": "manual_20261024",
                   "sector": "", "industry_boards": [], "concept_boards": [],
                   "business_summary": "", "updated_at": "2026-10-24 12:00:00"}
            data[code] = rec
            log.append((code, name, "（不在名单）→ 新建行"))
        if cat and not _has(rec):
            rec["jiuyan_category"] = cat
            rec["jiuyan_concept"] = con
            log.append((code, name, f"→ {cat}/{con}"))
        elif cat and _has(rec):
            skipped.append((code, name, "已有概念"))

    print(f"改动 {len(log)} 只：")
    for x in log:
        print(f"  {x[0]} {x[1]}  {x[2]}")
    if skipped:
        print(f"\n跳过 {len(skipped)}：")
        for x in skipped:
            print(f"  {x[0]} {x[1]}  {x[2]}")
    print(f"\n合不进现有板块、未动（涨停≥5次）{len(UNPLACED)} 只：")
    for c, (n, k, why) in sorted(UNPLACED.items(), key=lambda x: -x[1][1]):
        print(f"  {c} {n} {k:2d}次 —— {why}")

    if not apply:
        print("\n(dry-run，未写文件；加 --apply 执行)")
        return
    import os
    if not os.path.exists(BAK):      # 不覆盖首次备份（二次运行会把改后的文件盖掉原件）
        shutil.copy2(SRC, BAK)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\n已写入。备份: {BAK}")


if __name__ == "__main__":
    main()
