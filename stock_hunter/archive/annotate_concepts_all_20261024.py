def main():
    apply = "--apply" in sys.argv
    data = json.load(open(SRC, encoding="utf-8"))

    def concepts(rec):
        out = []
        for i in list(range(1, 10)) + [0]:
            k = "jiuyan_concept" if i == 0 else f"jiuyan_concept{i}"
            v = rec.get(k)
            for t in (v if isinstance(v, list) else str(v or "").split("|")):
                t = str(t).strip()
                if t:
                    out.append(t)
        return out

    # 概念 -> 第一只成员
    first = {}
    for code, rec in data.items():
        if not isinstance(rec, dict):
            continue
        for c in concepts(rec):
            first.setdefault(c, code)

    done, skip, miss = [], [], []
    for con, text in DESC.items():
        code = first.get(con)
        if not code:
            miss.append(con)
            continue
        rec = data[code]
        d = rec.get("jiuyan_concept_desc")
        if not isinstance(d, dict):
            d = {}
        if str(d.get(con) or "").strip():
            skip.append((con, code))
            continue
        d[con] = text
        rec["jiuyan_concept_desc"] = d
        rec["updated_at"] = "2026-10-24 16:30:00"
        done.append((con, code, rec.get("name")))

    print(f"写入 {len(done)} 个概念；已有跳过 {len(skip)}；没有成员 {miss}")
    for con, code, name in done:
        print(f"  {con} → 写在 {code} {name}")
    if not apply:
        print("\n(dry-run，未写文件；加 --apply 执行)")
        return
    if not os.path.exists(BAK):
        shutil.copy2(SRC, BAK)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\n已写入。备份: {BAK}")


if __name__ == "__main__":
    main()
